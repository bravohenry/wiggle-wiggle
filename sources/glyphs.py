def _remap_y(table, fn):
    out = {}
    for ch, strokes in table.items():
        moved = []
        for s in strokes:
            pts = [(p[0], fn(p[1])) + tuple(p[2:]) for p in (s["p"] if isinstance(s, dict) else s)]
            moved.append({**s, "p": pts} if isinstance(s, dict) else pts)
        out[ch] = moved
    return out


