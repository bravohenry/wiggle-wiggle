def K(x, y):
    """转角点：样条在此断开，笔不抬。"""
    return (x, y, True)


def dot(x, y, w=1.18):
    """点：一笔极短的落笔，笔重略大成墨团。"""
    return {"p": [(x - 4, y - 5), (x + 4, y + 4)], "w": w, "dot": True}


def _mirror(strokes, axis):
    out = []
    for s in strokes:
        pts = s["p"] if isinstance(s, dict) else s
        flipped = [(axis - p[0], p[1]) + tuple(p[2:]) for p in pts]
        out.append({**s, "p": flipped} if isinstance(s, dict) else flipped)
    return out


